function DS = debye(r,q,f1,f2,f3)
DS = acac_eq(r(1),r(2),r(3),q,f1,f2,f3) + 2*acac_ax(r(4),r(5),r(6),q,f1,f2,f3) - ground(q,f1,f2,f3);
DS = q.*DS;
end

